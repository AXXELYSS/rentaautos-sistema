begin;
select set_config('rental.test_owner',gen_random_uuid()::text,true);
select set_config('rental.other_owner',gen_random_uuid()::text,true);
insert into auth.users(id,email) values(current_setting('rental.test_owner')::uuid,'operations-test@example.invalid'),(current_setting('rental.other_owner')::uuid,'operations-other@example.invalid');
set local role authenticated;
select set_config('request.jwt.claim.sub',current_setting('rental.test_owner'),true);
do $$
declare c uuid; d uuid; e uuid; b uuid; running uuid; quote jsonb; amount numeric; blocked boolean; day date:=(now() at time zone 'America/Lima')::date;
begin
  insert into public.rental_autos(placa,marca,modelo,anio,tarifa_diaria,kilometraje) values('OPS-001','Toyota','Corolla',2023,150,10000) returning id into c;
  insert into public.rental_autos(placa,marca,modelo,anio,tarifa_diaria,kilometraje) values('OPS-002','Honda','Civic',2024,180,10000) returning id into d;
  insert into public.rental_autos(placa,marca,modelo,anio,tarifa_diaria,kilometraje) values('OPS-003','Nissan','Sentra',2023,120,10000) returning id into e;
  insert into public.rental_reservas(auto_id,cliente_nombre,cliente_dni,fecha_inicio,fecha_fin,created_at)
    values(c,'Cliente de prueba','12345678',day+2,day+5,'2000-01-01') returning id into b;
  assert (select created_at::date from public.rental_reservas where id=b)=(now())::date,'Creation timestamp is server owned';
  update public.rental_autos set tarifa_diaria=200 where id=c;
  quote:=public.rental_quote_edit(c,day+2,day+6,b);
  assert (quote->>'total')::numeric=600,'Edit excludes itself and keeps agreed daily rate';
  update public.rental_reservas set fecha_fin=day+6 where id=b;
  assert (select total from public.rental_reservas where id=b)=600,'Edited total recalculated';
  insert into public.rental_reservas(auto_id,cliente_nombre,cliente_dni,fecha_inicio,fecha_fin) values(d,'Otra reserva','87654321',day+3,day+4);
  blocked:=false;
  begin update public.rental_reservas set auto_id=d where id=b;
  exception when exclusion_violation then blocked:=true; end;
  assert blocked,'Changing vehicle must still reject overlap';
  update public.rental_reservas set auto_id=e where id=b;
  assert (select total from public.rental_reservas where id=b)=480,'Vehicle change takes its rate';
  insert into public.rental_pagos(reserva_id,monto,metodo) values(b,200,'efectivo');
  blocked:=false;
  begin insert into public.rental_pagos(reserva_id,monto,metodo) values(b,281,'transferencia');
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Overpayment must fail';
  blocked:=false;
  begin update public.rental_reservas set fecha_fin=day+3 where id=b;
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Cannot reduce total below received money';
  blocked:=false;
  begin insert into public.rental_inspecciones(reserva_id,tipo,kilometraje,combustible) values(b,'salida',10000,100);
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Cannot hand over before pickup date';
  update public.rental_reservas set estado='cancelada' where id=b;
  blocked:=false;
  begin insert into public.rental_pagos(reserva_id,monto,metodo) values(b,10,'efectivo');
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Cannot charge cancelled booking';
  blocked:=false;
  begin insert into public.rental_pagos(reserva_id,tipo,monto,metodo) values(b,'reembolso',201,'efectivo');
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Cannot refund more than received';
  insert into public.rental_pagos(reserva_id,tipo,monto,metodo) values(b,'reembolso',200,'efectivo');
  select sum(case when tipo='pago' then monto else -monto end) into amount from public.rental_pagos where reserva_id=b;
  assert amount=0,'Refund returns balance to zero';
  blocked:=false;
  begin update public.rental_pagos set monto=1 where reserva_id=b;
  exception when insufficient_privilege then blocked:=true; end;
  assert blocked,'Payment history is append only';
  insert into public.rental_reservas(auto_id,cliente_nombre,cliente_dni,fecha_inicio,fecha_fin) values(e,'Cliente en alquiler','11223344',day,day+1) returning id into running;
  blocked:=false;
  begin insert into public.rental_inspecciones(reserva_id,tipo,kilometraje,combustible) values(running,'devolucion',10010,50);
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Return requires departure';
  blocked:=false;
  begin insert into public.rental_inspecciones(reserva_id,tipo,kilometraje,combustible) values(running,'salida',9999,100);
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Odometer cannot decrease';
  blocked:=false;
  begin insert into public.rental_inspecciones(reserva_id,tipo,kilometraje,combustible) values(running,'salida',10000,101);
  exception when check_violation then blocked:=true; end;
  assert blocked,'Fuel must be 0 through 100';
  insert into public.rental_inspecciones(reserva_id,tipo,kilometraje,combustible,observaciones) values(running,'salida',10000,100,'Sin daños');
  blocked:=false;
  begin update public.rental_reservas set fecha_fin=day+2 where id=running;
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Delivered booking cannot be edited';
  blocked:=false;
  begin update public.rental_reservas set estado='cancelada' where id=running;
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Delivered booking cannot be cancelled';
  blocked:=false;
  begin insert into public.rental_inspecciones(reserva_id,tipo,kilometraje,combustible) values(running,'devolucion',9990,50);
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Return odometer must not be below departure';
  insert into public.rental_inspecciones(reserva_id,tipo,kilometraje,combustible,observaciones) values(running,'devolucion',10080,75,'Retorno sin daños');
  assert (select estado from public.rental_reservas where id=running)='finalizada','Return closes rental';
  assert (select kilometraje from public.rental_autos where id=e)=10080,'Return updates vehicle odometer';
  blocked:=false;
  begin update public.rental_autos set kilometraje=9999 where id=e;
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Vehicle editor cannot roll back odometer';
  insert into public.rental_pagos(reserva_id,monto,metodo) values(running,120,'tarjeta');
  perform set_config('request.jwt.claim.sub',current_setting('rental.other_owner'),true);
  assert not exists(select 1 from public.rental_pagos where reserva_id in (b,running)),'RLS isolates payments';
  assert not exists(select 1 from public.rental_inspecciones where reserva_id=running),'RLS isolates inspections';
  blocked:=false;
  begin insert into public.rental_pagos(reserva_id,monto,metodo) values(running,1,'efectivo');
  exception when raise_exception then blocked:=true; end;
  assert blocked,'Cannot pay another office booking';
end $$;
reset role;
select 'PASS: 24 operations checks (editing, agreed rates, payment limits, refunds, odometer, fuel, lifecycle and RLS)' as result;
rollback;
